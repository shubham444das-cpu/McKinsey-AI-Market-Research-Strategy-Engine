"""
Core data model for the research pipeline.

These mirror the dossier's data assets (section 6.3): research request,
source record, evidence record, and report. Kept as plain dataclasses so
they serialize cleanly to session_state / JSON without extra tooling.
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import List, Optional
import uuid


def _new_id() -> str:
    return uuid.uuid4().hex[:10]


@dataclass
class ResearchTask:
    """One sub-question the planner wants answered, with its own search query."""
    id: str = field(default_factory=_new_id)
    question: str = ""
    search_query: str = ""
    expected_evidence_type: str = ""  # e.g. "market size stat", "competitor move"


@dataclass
class ResearchPlan:
    objective: str = ""
    tasks: List[ResearchTask] = field(default_factory=list)


@dataclass
class SourceRecord:
    id: str = field(default_factory=_new_id)
    task_id: str = ""
    url: str = ""
    title: str = ""
    snippet: str = ""
    fetched_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    raw_text: str = ""       # truncated page text used for extraction
    fetch_ok: bool = True
    fetch_error: Optional[str] = None


@dataclass
class EvidenceRecord:
    id: str = field(default_factory=_new_id)
    source_id: str = ""
    task_id: str = ""
    claim: str = ""
    excerpt: str = ""
    entity: str = ""
    topic: str = ""
    url: str = ""
    confidence: float = 0.0          # 0-1, from validator
    validation_notes: str = ""
    flags: List[str] = field(default_factory=list)  # e.g. ["stale", "unsupported", "duplicate"]
    accepted: bool = True


@dataclass
class ThemeGroup:
    theme: str = ""
    evidence_ids: List[str] = field(default_factory=list)
    summary: str = ""


@dataclass
class Report:
    executive_summary: str = ""
    key_findings: str = ""
    market_signals: str = ""
    competitor_observations: str = ""
    implications: str = ""
    recommendations: str = ""
    evidence_appendix_md: str = ""
    human_review_note: str = (
        "This report was generated by an AI research pipeline. Claims are cited "
        "to public sources but have not been independently verified. Review "
        "before client use."
    )


@dataclass
class ResearchJob:
    id: str = field(default_factory=_new_id)
    query: str = ""
    market: str = ""
    geography: str = ""
    timeframe: str = ""
    competitors: str = ""
    depth: str = "Standard"  # Quick / Standard / Deep
    status: str = "intake"   # intake -> planning -> browsing -> extraction ->
                              # validation -> aggregation -> report -> done
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    plan: Optional[ResearchPlan] = None
    sources: List[SourceRecord] = field(default_factory=list)
    evidence: List[EvidenceRecord] = field(default_factory=list)
    themes: List[ThemeGroup] = field(default_factory=list)
    report: Optional[Report] = None
    related_memory: List[dict] = field(default_factory=list)  # RAG-recalled prior findings (utils.memory)

    log: List[str] = field(default_factory=list)
    search_errors: List[str] = field(default_factory=list)  # raw provider errors from the browsing stage

    def add_log(self, message: str) -> None:
        ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
        self.log.append(f"[{ts}] {message}")

    def to_dict(self) -> dict:
        return asdict(self)
